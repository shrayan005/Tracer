"""
File storage (integration layer): where ORIGINAL files live (downloaded PDFs/XML, later user uploads).

Content-addressed: a file's name is its SHA-256 fingerprint, never a name a user chose.
  - The same file stored twice (two topics, two users) is kept ONCE.
  - Keys are generated by code and checked against a strict pattern, so a filename like
    "../../etc/passwd" can never become a path (no path traversal).

FileStorage is an interface: LocalFileStorage (a folder) now, an S3/MinIO class when deployed.
Services only use the interface, so switching is one line in dependencies.py.
"""

import asyncio
import hashlib
import os
import re
import uuid
from pathlib import Path
from typing import Protocol

# "3f/a9/3fa9...64 hex chars....pdf": two folder levels so no folder holds millions of files
KEY_PATTERN = re.compile(r"^[0-9a-f]{2}/[0-9a-f]{2}/[0-9a-f]{64}\.[a-z0-9]{1,5}$")


def sha256_of(data: bytes) -> str:
    """The file's fingerprint: identical bytes -> identical 64-character hex string."""
    return hashlib.sha256(data).hexdigest()


def make_key(sha256: str, extension: str) -> str:
    """'3fa9c1...', 'pdf' -> '3f/a9/3fa9c1....pdf'"""
    key = f"{sha256[:2]}/{sha256[2:4]}/{sha256}.{extension.lower().lstrip('.')}"
    if not KEY_PATTERN.match(key):
        raise ValueError(f"invalid storage key: {key!r}")
    return key


class FileStorage(Protocol):
    async def save(self, key: str, data: bytes) -> None: ...
    async def read(self, key: str) -> bytes: ...
    async def exists(self, key: str) -> bool: ...
    async def delete(self, key: str) -> None: ...


class LocalFileStorage:
    """Files in a folder on this machine (inside WSL), e.g. research_app/data/files/."""

    def __init__(self, root: Path | str):
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        if not KEY_PATTERN.match(key):                # only keys made by make_key() are accepted
            raise ValueError(f"invalid storage key: {key!r}")
        return self.root / key

    # Disk I/O blocks, so it runs in a worker thread (asyncio.to_thread) to keep the event loop free.

    async def save(self, key: str, data: bytes) -> None:
        await asyncio.to_thread(self._save_sync, self._path(key), data)

    async def read(self, key: str) -> bytes:
        return await asyncio.to_thread(self._path(key).read_bytes)

    async def exists(self, key: str) -> bool:
        return await asyncio.to_thread(self._path(key).exists)

    async def delete(self, key: str) -> None:
        await asyncio.to_thread(self._path(key).unlink, missing_ok=True)

    @staticmethod
    def _save_sync(path: Path, data: bytes) -> None:
        if path.exists():                             # same key = same bytes: nothing to do
            return
        path.parent.mkdir(parents=True, exist_ok=True)
        temp = path.with_name(f".{path.name}.{uuid.uuid4().hex}.tmp")
        temp.write_bytes(data)
        os.replace(temp, path)                        # atomic: readers never see a half-written file
